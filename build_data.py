"""Generate data/questions.js from the master question bank.

Handles all question types: mcq_single, mcq_multi, assertion_reason, matching.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BANK = ROOT / "UPPCS_2026_Polity_Question_Bank.json"
OUT = ROOT / "data" / "questions.js"

LETTER_TO_INDEX = {"A": 0, "B": 1, "C": 2, "D": 3, "E": 4}
LETTER_TO_INDEX_inv = {v: k for k, v in LETTER_TO_INDEX.items()}

AR_OPTIONS = [
    {"en": "Both A and R are true and R is the correct explanation of A",
     "hi": "A और R दोनों सत्य हैं और R, A की सही व्याख्या है"},
    {"en": "Both A and R are true but R is NOT the correct explanation of A",
     "hi": "A और R दोनों सत्य हैं परंतु R, A की सही व्याख्या नहीं है"},
    {"en": "A is true but R is false",
     "hi": "A सत्य है परंतु R असत्य है"},
    {"en": "A is false but R is true",
     "hi": "A असत्य है परंतु R सत्य है"},
    {"en": "Both A and R are false",
     "hi": "A और R दोनों असत्य हैं"},
]


def option_to_html(letter, opt):
    return {"en": opt.get("en", ""), "hi": opt.get("hi", "")}


def get_options(q):
    """Get options as dict {letter: {en, hi}} from various formats."""
    opts = q.get("options")
    if opts is None:
        opts = q.get("opts", {})
    if isinstance(opts, list):
        # List format: [{en, hi}, ...] -> {A: {...}, B: {...}, ...}
        return {LETTER_TO_INDEX_inv[i]: o for i, o in enumerate(opts) if isinstance(o, dict)}
    return opts or {}


def get_correct(q, qtype):
    """Get correct answer as letter(s)."""
    c = q.get("correct")
    if isinstance(c, int):
        return LETTER_TO_INDEX_inv.get(c, str(c))
    if isinstance(c, list):
        return [LETTER_TO_INDEX_inv.get(x, x) for x in c]
    return c  # Already a letter string like "A" or "AB"


def question_to_obj(q):
    qtype = q.get("type", "mcq_single")
    obj = {
        "id": q["id"],
        "section": q["chapter"],
        "sub": q["subtopic"],
        "type": qtype,
        "qEn": q.get("question_en", ""),
        "qHi": q.get("question_hi", ""),
        "cEn": q.get("correct_en", ""),
        "cHi": q.get("correct_hi", ""),
        "eEn": q.get("explanation_en", ""),
        "eHi": q.get("explanation_hi", ""),
        "ref": q.get("reference", ""),
    }

    opts = get_options(q)

    if qtype == "mcq_single":
        obj["opts"] = [option_to_html(k, opts.get(k, {"en": "", "hi": ""})) for k in ("A", "B", "C", "D")]
        obj["correct"] = LETTER_TO_INDEX[get_correct(q, qtype)]
    elif qtype == "mcq_multi":
        obj["opts"] = [option_to_html(k, opts.get(k, {"en": "", "hi": ""})) for k in ("A", "B", "C", "D")]
        obj["correct"] = [LETTER_TO_INDEX[c] for c in get_correct(q, qtype)]
    elif qtype == "assertion_reason":
        obj["assertionEn"] = q.get("assertion_en", "")
        obj["assertionHi"] = q.get("assertion_hi", "")
        obj["reasonEn"] = q.get("reason_en", "")
        obj["reasonHi"] = q.get("reason_hi", "")
        obj["opts"] = [{"en": o["en"], "hi": o["hi"]} for o in AR_OPTIONS]
        obj["correct"] = LETTER_TO_INDEX[get_correct(q, qtype)]
    elif qtype == "matching":
        col1 = q.get("col1") or q.get("column1") or []
        col2 = q.get("col2") or q.get("column2") or []
        obj["col1"] = [{"en": it.get("en", ""), "hi": it.get("hi", "")} for it in col1]
        obj["col2"] = [{"en": it.get("en", ""), "hi": it.get("hi", "")} for it in col2]
        obj["opts"] = [{"en": it.get("en", ""), "hi": it.get("hi", "")} for it in col2]
        obj["correct"] = q.get("correct_mapping", {})
    return obj


def main():
    data = json.load(open(BANK, encoding="utf-8"))
    questions = data["questions"]
    sections = {}
    order = []
    for q in questions:
        sec = q.get("chapter", "Uncategorized")
        if sec not in sections:
            sections[sec] = []
            order.append(sec)
        sections[sec].append(question_to_obj(q))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    lines = ["// Auto-generated by build_data.py from UPPCS_2026_Polity_Question_Bank.json",
             "window.SECTIONS = " + json.dumps(sections, ensure_ascii=False, indent=2) + ";",
             "window.SECTION_ORDER = " + json.dumps(order, ensure_ascii=False) + ";",
             "window.ALL_QUESTIONS = " + json.dumps([q for sec in order for q in sections[sec]], ensure_ascii=False, indent=2) + ";",
             ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    counts = {}
    for q in questions:
        counts[q.get("type", "mcq_single")] = counts.get(q.get("type", "mcq_single"), 0) + 1
    print(f"Wrote {OUT}: {len(order)} sections, {len(questions)} questions "
          f"({counts})")


if __name__ == "__main__":
    main()